"""Deterministic, clearly labelled synthetic datasets for demos, tests and benchmarks.

All generators take an explicit ``seed`` and an ``as_of`` timestamp, so the same call always
returns identical data. Every scenario returns a healthy baseline, a modified batch and the
ground truth of what was injected, which the benchmark uses to score detection.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Any

import numpy as np
import pandas as pd

SYNTHETIC_LABEL = "SYNTHETIC — generated by datasentry_core.synthetic with a fixed seed"
DEFAULT_AS_OF = datetime(2026, 1, 15, 12, 0, 0)

SEGMENTS = ["retail", "smb", "enterprise"]
SEGMENT_P = [0.6, 0.3, 0.1]
CHANNELS = ["web", "mobile", "branch"]
CHANNEL_P = [0.5, 0.4, 0.1]
CURRENCIES = ["USD", "EUR", "GBP"]
CURRENCY_P = [0.55, 0.3, 0.15]
COUNTRIES = ["US", "GB", "DE", "FR", "IN"]
COUNTRY_P = [0.4, 0.2, 0.15, 0.15, 0.1]


@dataclass
class Scenario:
    name: str
    title: str
    description: str
    baseline: pd.DataFrame
    modified: pd.DataFrame
    injected: list[dict[str, Any]] = field(default_factory=list)
    expected_rules: list[dict[str, Any]] = field(default_factory=list)


def customers(n: int = 800, seed: int = 7) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    ids = [f"C{i:05d}" for i in range(1, n + 1)]
    return pd.DataFrame({
        "customer_id": ids,
        "segment": rng.choice(SEGMENTS, n, p=SEGMENT_P),
        "country": rng.choice(COUNTRIES, n, p=COUNTRY_P),
        "signup_date": [(DEFAULT_AS_OF - timedelta(days=int(d))).date().isoformat() for d in rng.integers(30, 1500, n)],
    })


def transactions(n: int = 2000, seed: int = 42, as_of: datetime = DEFAULT_AS_OF, n_customers: int = 800,
                 id_offset: int = 0, days: int = 7) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    cust_rng = np.random.default_rng(7)
    seg_by_customer = cust_rng.choice(SEGMENTS, n_customers, p=SEGMENT_P)
    cust_idx = rng.integers(0, n_customers, n)
    seconds = np.sort(rng.integers(0, days * 86400, n))
    start = as_of - timedelta(days=days)
    amount = np.round(rng.lognormal(mean=3.6, sigma=0.7, size=n), 2)
    return pd.DataFrame({
        "transaction_id": [f"T{id_offset + i:07d}" for i in range(1, n + 1)],
        "customer_id": [f"C{i + 1:05d}" for i in cust_idx],
        "event_time": [(start + timedelta(seconds=int(s))).isoformat(sep=" ") for s in seconds],
        "amount": amount,
        "currency": rng.choice(CURRENCIES, n, p=CURRENCY_P),
        "segment": seg_by_customer[cust_idx],
        "channel": rng.choice(CHANNELS, n, p=CHANNEL_P),
        "country": rng.choice(COUNTRIES, n, p=COUNTRY_P),
        "items": rng.poisson(2.2, n) + 1,
        "email": [f"user{i + 1}@example.com" for i in cust_idx],
    })


def default_rules() -> list[dict[str, Any]]:
    """Quality rules that describe a healthy transactions batch."""
    return [
        {"name": "transaction_id present", "rule_type": "not_null", "columns": ["transaction_id"], "severity": "critical"},
        {"name": "transaction_id unique", "rule_type": "unique", "columns": ["transaction_id"], "severity": "critical"},
        {"name": "segment present", "rule_type": "not_null", "columns": ["segment"], "severity": "warning", "config": {"max_failure_pct": 1}},
        {"name": "amount within range", "rule_type": "range", "columns": ["amount"], "severity": "warning",
         "config": {"min": 0, "max": 5000}},
        {"name": "known currency", "rule_type": "allowed_values", "columns": ["currency"], "severity": "critical",
         "config": {"values": CURRENCIES}},
        {"name": "email format", "rule_type": "regex", "columns": ["email"], "severity": "info",
         "config": {"pattern": r"[^@\s]+@[^@\s]+\.[a-z]{2,}"}},
        {"name": "no duplicate rows", "rule_type": "duplicate_rows", "columns": [], "severity": "warning"},
        {"name": "fresh within 48h", "rule_type": "freshness", "columns": ["event_time"], "severity": "critical",
         "config": {"max_age_seconds": 48 * 3600}},
        {"name": "batch size", "rule_type": "row_count", "columns": [], "severity": "warning",
         "config": {"min_rows": 500, "max_rows": 100000}},
        {"name": "schema contract", "rule_type": "schema", "columns": [], "severity": "critical",
         "config": {"expected_columns": [{"name": c} for c in
                    ["transaction_id", "customer_id", "event_time", "amount", "currency", "segment", "channel"]]}},
    ]


def _with(df: pd.DataFrame) -> pd.DataFrame:
    return df.copy().reset_index(drop=True)


def scenario(name: str, seed: int = 42, n: int = 2000, as_of: datetime = DEFAULT_AS_OF) -> Scenario:
    """Build one named scenario. The modified batch is a fresh draw (different seed) plus the injection,
    so healthy sampling variation is present as it would be in production."""
    base = transactions(n, seed, as_of)
    cur = transactions(n, seed + 1000, as_of, id_offset=n)
    rng = np.random.default_rng(seed + 7)
    injected: list[dict[str, Any]] = []
    title, desc = name, ""
    if name == "healthy":
        title, desc = "Healthy batch", "A new batch from the same process. Nothing injected (control)."
    elif name == "missing_spike":
        idx = rng.choice(n, int(0.3 * n), replace=False)
        cur.loc[idx, "segment"] = None
        injected = [{"kind": "missing", "column": "segment"}]
        title, desc = "Missing-value spike", "30% of 'segment' values are blanked out."
    elif name == "schema_change":
        cur = cur.rename(columns={"amount": "transaction_amount"}).drop(columns=["channel"])
        injected = [{"kind": "schema", "column": "amount"}, {"kind": "schema", "column": "channel"}]
        title, desc = "Schema change", "'amount' renamed to 'transaction_amount' and 'channel' removed."
    elif name == "duplicates":
        dup = cur.sample(frac=0.08, random_state=seed)
        cur = pd.concat([cur, dup]).sort_values("event_time").reset_index(drop=True)
        injected = [{"kind": "duplicates", "column": None}]
        title, desc = "Duplicate records", "8% of rows are replayed (exact duplicates)."
    elif name == "unexpected_categories":
        idx = rng.choice(n, int(0.1 * n), replace=False)
        cur.loc[idx, "currency"] = rng.choice(["JPY", "XXX"], len(idx))
        injected = [{"kind": "category", "column": "currency"}]
        title, desc = "Unexpected categories", "10% of 'currency' values are JPY or the invalid code XXX."
    elif name == "numeric_drift":
        cur["amount"] = np.round(cur["amount"] * 1.6 + 15, 2)
        injected = [{"kind": "drift", "column": "amount"}]
        title, desc = "Numerical distribution drift", "'amount' is scaled by 1.6 and shifted by +15."
    elif name == "stale_ingestion":
        ts = pd.to_datetime(cur["event_time"]) - timedelta(days=5)
        cur["event_time"] = ts.dt.strftime("%Y-%m-%d %H:%M:%S")
        injected = [{"kind": "freshness", "column": "event_time"}]
        title, desc = "Stale ingestion", "The batch's newest record is 5 days old."
    elif name == "category_shift":
        cur["channel"] = rng.choice(CHANNELS, n, p=[0.2, 0.75, 0.05])
        injected = [{"kind": "drift", "column": "channel"}]
        title, desc = "Categorical distribution shift", "'channel' mix moves from web-heavy to mobile-heavy."
    else:
        raise ValueError(f"unknown scenario '{name}'")
    return Scenario(name, title, desc, _with(base), _with(cur), injected, default_rules())


SCENARIOS = ["healthy", "missing_spike", "schema_change", "duplicates", "unexpected_categories",
             "numeric_drift", "stale_ingestion", "category_shift"]


