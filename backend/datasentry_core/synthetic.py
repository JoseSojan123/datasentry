CREDIT_FEATURES = ["income", "debt_ratio", "utilization", "late_payments", "age", "employment_type"]


def credit_applications(n: int, seed: int, shift: float = 0.0, concept_change: bool = False) -> pd.DataFrame:
    """Synthetic loan applications with a default label generated from a known logistic model.

    ``shift`` moves the input distribution (input drift); ``concept_change`` alters the relationship
    between inputs and label (performance degradation without obvious input drift).
    """
    rng = np.random.default_rng(seed)
    income = rng.lognormal(10.8 - 0.25 * shift, 0.45, n)
    debt_ratio = np.clip(rng.beta(2, 5, n) + 0.12 * shift, 0, 1.5)
    utilization = np.clip(rng.beta(2, 3, n) + 0.15 * shift, 0, 1)
    late = rng.poisson(0.6 + 0.8 * shift, n)
    age = np.clip(rng.normal(41, 11, n), 18, 85).round()
    employment = rng.choice(["salaried", "self_employed", "contract", "unemployed"], n,
                            p=[0.62 - 0.1 * shift, 0.18, 0.15, 0.05 + 0.1 * shift])
    z = (-2.0 - 0.9 * (np.log(income) - 10.8) + 2.2 * debt_ratio + 1.6 * utilization + 0.55 * late
         - 0.01 * (age - 40) + np.where(employment == "unemployed", 1.0, 0.0))
    if concept_change:
        z = -1.2 + 2.5 * (age < 30) - 1.0 * utilization + 0.3 * late
    p = 1 / (1 + np.exp(-z))
    y = (rng.random(n) < p).astype(int)
    return pd.DataFrame({
        "application_id": [f"A{seed:03d}{i:06d}" for i in range(n)],
        "income": income.round(2), "debt_ratio": debt_ratio.round(4), "utilization": utilization.round(4),
        "late_payments": late, "age": age, "employment_type": employment, "defaulted": y,
    })
